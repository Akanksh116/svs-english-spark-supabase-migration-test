export function pickDailyWord(date = new Date()): DailyWord {
  const day = Math.floor(
    Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()) / 86400000,
  );
  return DAILY_WORDS[day % DAILY_WORDS.length];
}
